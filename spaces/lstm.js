// RNN / LSTM: сеть с памятью читает отзыв слово за словом. Ворота забывания и отрицание видны по шагам.
import { tokenize, sigmoid, vocabularyTable, lookupForm } from '../src/engine/models/text.js';

const DIMS = ['тональность', 'отрицание', '«но»'];
// [тональность −1..1, это отрицание?, это противопоставление?]
const V = {
  'отличный': [1, 0, 0], 'отлично': [1, 0, 0], 'хороший': [0.8, 0, 0], 'хорошо': [0.8, 0, 0], 'прекрасный': [1, 0, 0],
  'интересный': [0.7, 0, 0], 'интересно': [0.7, 0, 0], 'нравится': [0.8, 0, 0], 'понравился': [0.8, 0, 0],
  'люблю': [0.9, 0, 0], 'рекомендую': [0.9, 0, 0], 'смешной': [0.6, 0, 0], 'красивый': [0.7, 0, 0], 'добрый': [0.7, 0, 0],
  'плохой': [-0.8, 0, 0], 'плохо': [-0.8, 0, 0], 'ужасный': [-1, 0, 0], 'ужасно': [-1, 0, 0], 'скучный': [-0.7, 0, 0],
  'скучно': [-0.7, 0, 0], 'глупый': [-0.7, 0, 0], 'затянутый': [-0.6, 0, 0], 'медленный': [-0.5, 0, 0], 'ненавижу': [-0.9, 0, 0],
  'не': [0, 1, 0], 'нет': [0, 1, 0], 'никогда': [0, 1, 0],
  'но': [0, 0, 1], 'однако': [0, 0, 1], 'зато': [0, 0, 1],
  'фильм': [0, 0, 0], 'книга': [0, 0, 0], 'актеры': [0, 0, 0], 'сюжет': [0, 0, 0], 'финал': [0, 0, 0], 'сначала': [0, 0, 0],
  'потом': [0, 0, 0], 'было': [0, 0, 0], 'был': [0, 0, 0], 'совсем': [0, 0, 0], 'очень': [0, 0, 0], 'мне': [0, 0, 0], 'я': [0, 0, 0], 'и': [0, 0, 0],
};

export default {
  meta: {
    id: 'lstm',
    title: 'RNN и LSTM: сеть с памятью',
    category: 'nlp',
    order: 30,
    level: 2,
    fidelity: 'real',
    summary: 'Сеть читает отзыв по одному слову и хранит «память». Видно, как ворота забывания стирают её на слове «но», а отрицание переворачивает смысл.',
    uses: 'Распознавание речи, машинный перевод и предсказание текста до эпохи трансформеров; сейчас — прогноз временных рядов и потоковые данные с датчиков.',
    tags: ['NLP', 'RNN', 'LSTM', 'память', 'последовательности'],
    preview: { tokens: ['скучно', 'но', 'отлично'] },
  },

  type: 'tokens',
  mode: 'rnn',
  runLabel: 'Прочитать текст',
  resultTitle: 'Тональность',
  presets: [
    'фильм скучный, но актеры отличные',
    'мне не нравится',
    'совсем не плохо',
    'сначала было интересно, но потом скучно',
    'я никогда не рекомендую',
  ],

  process(text) {
    const words = tokenize(text);
    const base = words.map(w => lookupForm(V, w));
    const tokens = words.map((w, i) => ({ text: w, known: !!base[i] }));
    const embeddings = base.map(b => (b ? V[b] : [0, 0, 0]));
    let c = 0, m = 0;
    const steps = embeddings.map(([s, n, b], i) => {
      // LSTM-подобная ячейка, веса заданы вручную:
      const f = sigmoid(-7 * b + 3.5);                // забывание: на «но» почти 0 — память стирается
      const inp = sigmoid(7 * Math.abs(s) - 3.5);     // запись: открыта только для оценочных слов
      const g = Math.tanh(2.5 * s * (1 - 2 * m));     // что записать: знак переворачивается, если помним «не»
      c = f * c + inp * g;
      const prevM = m;
      // «не» запоминается до ближайшего оценочного слова. В русском «никогда не», «совсем не» — одно отрицание, а не двойное
      m = n > 0.5 ? 1 : Math.abs(s) > 0.3 ? 0 : m * f;
      let note = '';
      if (b > 0.5) note = '«Но» закрывает ворота забывания (f ≈ 0): всё, что было до него, почти стирается — важнее то, что после.';
      else if (n > 0.5) note = prevM > 0.5 ? 'Ещё одно отрицательное слово: в русском «никогда не» — это одно (усиленное) отрицание, память «не» остаётся включённой.' : 'Отрицание записано во вторую ячейку памяти: следующее оценочное слово будет перевёрнуто.';
      else if (Math.abs(s) > 0.3) note = prevM > 0.5 ? `Оценочное слово после «не»: его знак перевёрнут (g = ${g.toFixed(2)}).` : 'Оценочное слово: ворота записи открыты, в память добавляется его тональность.';
      else note = 'Нейтральное слово: ворота записи почти закрыты, память почти не меняется.';
      return { h: [Math.tanh(c), m], c: [c], gates: { f, i: inp, o: 1, g }, note };
    });
    const hT = steps.at(-1)?.h[0] ?? 0;
    const p = sigmoid(4 * hT);
    return {
      tokens, dims: DIMS, embeddings, steps,
      stateDims: ['тональность', 'помню «не»'],
      outputs: [
        { label: 'Позитив', value: p, note: `sigmoid(4·h) при h = ${hT.toFixed(3)} — последнем состоянии памяти.` },
        { label: 'Негатив', value: 1 - p },
      ],
      html: `<p>${p > 0.6 ? 'Итог: <b class="pos">позитив</b>' : p < 0.4 ? 'Итог: <b class="neg">негатив</b>' : 'Итог: <b>нейтрально</b>'} (${Math.round(p * 100)}%).
        Сеть прочитала ${tokens.length} слов по порядку; ответ зависит только от последнего состояния памяти.</p>
        <p class="small muted">Наведите курсор на ячейки: в каждой видны ворота f (забыть), i (записать) и новое содержимое памяти.
        Сравните с пространством <a href="space.html?id=sentiment">«Анализ тональности»</a>: «мешок слов» не понимает «не» и «но».</p>`,
    };
  },

  vocabularyHtml: vocabularyTable(V, DIMS),

  intro: `<p>Рекуррентная сеть (RNN) читает текст <b>по одному слову</b> и после каждого обновляет «память» — скрытое состояние.
    LSTM добавляет к памяти <b>ворота</b>: что забыть, что записать, что выдать. Здесь ячейка маленькая и её веса заданы вручную,
    чтобы каждое число было понятно, но формулы — настоящие формулы LSTM.</p>`,

  sections: [
    {
      title: 'Формулы ячейки',
      open: false,
      html: `<ul class="steps">
          <li><b>f</b> = σ(−7·«но» + 3,5) — ворота забывания</li>
          <li><b>i</b> = σ(7·|тональность| − 3,5) — ворота записи</li>
          <li><b>g</b> = tanh(2,5 · тональность · (1 − 2·помню_не)) — новое содержимое</li>
          <li><b>c</b> = f · c<sub>прошл</sub> + i · g — обновлённая память</li>
          <li><b>h</b> = tanh(c) — выход ячейки; итог = σ(4·h<sub>последний</sub>)</li>
        </ul>
        <p class="muted small">В настоящей LSTM все эти веса — матрицы, которые выучиваются на данных, а память — вектор из сотен чисел.</p>`,
    },
  ],
};
